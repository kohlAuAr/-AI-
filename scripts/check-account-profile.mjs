import assert from 'node:assert/strict';
import { createSessionClient } from './http-session.mjs';

const base = process.env.SMOKE_BASE_URL || 'http://127.0.0.1:5178';
const client = createSessionClient(base), fresh = createSessionClient(base), other = createSessionClient(base);
const body = (method, value) => ({ method, headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(value) });
const username = `profile_${Date.now().toString(36)}`;
const input = { username, password: 'CampusDemo123!', name: '账号资料验收（虚构）', major: '软件工程' };
const login = (session, name) => session.json('/api/auth/login', { method: 'POST', body: new URLSearchParams({ username: name, password: input.password }) });

await client.json('/api/profile', {}, 401);
await client.json('/api/auth/register', body('POST', { ...input, username: 'bad account' }), 400);
await client.json('/api/auth/register', body('POST', { ...input, password: 'short' }), 400);
const created = await client.json('/api/auth/register', body('POST', { ...input, role: 'PLATFORM_ADMIN' }));
assert.equal(created.role, 'STUDENT');
assert(!('password' in created) && !('passwordHash' in created));
assert.equal((await client.json('/api/auth/session')).user, null, 'registration requires a separate login');
await client.json('/api/auth/register', body('POST', input), 409);
await login(client, username);
assert.equal((await client.json('/api/auth/session')).user.id, created.id);
const update = { name: '资料已保存（虚构）', major: '数字媒体', interests: ['摄影', '户外'], availableTime: '周三晚上、周末下午' };
const saved = await client.json('/api/profile', body('PUT', update));
assert.equal(saved.id, created.id); assert.equal(saved.name, update.name);
assert.deepEqual(saved.interests, update.interests); assert.equal(saved.availableTime, update.availableTime);
assert.equal((await client.json('/api/auth/session')).user.name, update.name);
await client.json('/api/profile', body('PUT', { ...update, name: ' ' }), 400);
assert.equal((await client.json('/api/profile')).name, update.name, 'invalid save preserves existing profile');
await client.json('/api/manage/clubs', {}, 403);
await client.json('/api/platform/banners', {}, 403);
await client.json('/api/auth/logout', { method: 'POST' });
await client.json('/api/profile', {}, 401);
await login(fresh, username);
const restored = await fresh.json('/api/profile');
assert.equal(restored.name, update.name); assert.equal(restored.major, update.major);
assert.deepEqual(restored.interests, update.interests); assert.equal(restored.availableTime, update.availableTime);
await login(other, 'student');
assert.notEqual((await other.json('/api/profile')).id, created.id, 'another session sees only its own profile');
await fresh.json('/api/profile', body('PUT', { ...update, interests: [], availableTime: '' }));
assert.deepEqual((await fresh.json('/api/profile')).interests, [], 'optional interests may be cleared');
await fresh.json('/api/profile', body('PUT', update));
await fresh.json('/api/auth/logout', { method: 'POST' });
await other.json('/api/auth/logout', { method: 'POST' });
console.log(`PASS: real HTTP registration/profile chain through ${base}; retained synthetic student ${username}, id ${created.id}. Duplicate/invalid registration, CSRF, student-only role, save/clear, fresh-session persistence and account isolation checked. No browser clicks or process-restart persistence claimed.`);
